from schemas.ai import QuestionAnalysis
from langchain_core.prompts import ChatPromptTemplate
from core.ai import get_llm

QUESTION_CLASSIFY_PROMPT = """
คุณคือ AI ผู้เชี่ยวชาญด้านการสกัดข้อมูลและจัดหมวดหมู่คำถาม
        
[ภารกิจ]
วิเคราะห์คำถามของผู้ใช้ และสกัดข้อมูลลงในโครงสร้างที่กำหนด
- วิเคราะห์ข้อมูลเฉพาะที่มีอยู่จริงในข้อความเท่านั้น ห้ามคาดเดาหรือสร้างข้อมูลขึ้นมาเอง

[กฎการสกัดชื่อบุคคลและชื่อบริษัท]
1. ชื่อบุคคล:
   - สกัดเฉพาะชื่อ-นามสกุล หรือชื่อเรียกของบุคคล
   - ตัดคำนำหน้าชื่อ คำสรรพนาม หรือตำแหน่งออกทั้งหมด (เช่น คุณ, นาย, นาง, นางสาว, ดร., ท่าน, ผอ., พี่ ฯลฯ)
   
2. ชื่อบริษัท/องค์กร:
   - สกัดเฉพาะชื่อเฉพาะของบริษัทหรือองค์กร
   - ตัดคำนำหน้าชื่อบริษัทออกทั้งหมด (เช่น บริษัท ฯลฯ)

[กฎการจัดหมวดหมู่คำถาม]
- personal_contact: คำถามที่ต้องการขอข้อมูลติดต่อบุคคล เช่น อีเมล เบอร์โทรศัพท์
- mou: คำถามเกี่ยวกับ MOU (สถานะ สัญญา ข้อตกลง หรือเอกสาร) ของบริษัท
- relationship: คำถามเกี่ยวกับความสัมพันธ์ เครือข่ายการติดต่อ หรือผู้เชื่อมโยงระหว่างบริษัทกับบุคคล เช่น 'บริษัท A มาจากทางไหน', 'บริษัท A มาจาก/สนิทกับอาจารย์ท่านไหน'
- activity: คำถามเกี่ยวกับประวัติการเข้าร่วมกิจกรรม หรือความร่วมมือต่างๆ ของบริษัท
- history: คำถามเกี่ยวกับประวัติของบริษัท เช่น บริษัท A เคสล่าสุดคืออะไร, บริษัท A เคยมีเคสอะไรบ้าง
- other: คำถามทั่วไปที่ไม่เข้าพวก
"""

prompt_template = ChatPromptTemplate.from_messages([
    ("system", QUESTION_CLASSIFY_PROMPT),
    ("user", "Question:\n{question}")
])

_chain = None

def get_classify_chain():
    global _chain
    if _chain is None:
        _chain = prompt_template | get_llm().with_structured_output(
            QuestionAnalysis, include_raw=True
        )
    return _chain
