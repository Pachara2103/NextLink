-- --------------------------------------------------------------------------
-- บอกผลให้คนที่รันเห็น
--
-- มีกรณีหนึ่งที่ไฟล์นี้ "สำเร็จ" แต่ไม่ได้ทำอะไรและหน้าจอยังเปิดไม่ได้: เทอม
-- ของปี/ภาคนี้เคยเปิดแล้วถูกปิดไป INSERT ข้างบนจึงไม่ทำอะไร (ถูกแล้ว - การ
-- รันสคริปต์ตั้งค่าไม่ควรไปเปิดเทอมที่คนตั้งใจปิด) แต่ถ้าไม่บอก คนที่รันจะ
-- เห็นแค่ COMMIT แล้วไปงงที่หน้าเว็บ
-- --------------------------------------------------------------------------
DO $$
DECLARE
    term_label text;
    ready_rooms int;
    approval_rooms int;
BEGIN
    SELECT format('%s/%s', semester, year) INTO term_label
    FROM elective_terms WHERE status = 'current';

    SELECT
        count(*) FILTER (WHERE tier = 'ready' AND is_active),
        count(*) FILTER (WHERE tier = 'needs_approval' AND is_active)
    INTO ready_rooms, approval_rooms
    FROM elective_rooms;

    RAISE NOTICE 'ห้องที่ใช้ได้: % ห้องของภาค + % ห้องที่ต้องยื่นขอ', ready_rooms, approval_rooms;

    IF term_label IS NULL THEN
        RAISE NOTICE 'ยังไม่มีเทอมที่กำลังจัด (ปี/ภาคนี้เคยเปิดแล้วปิดไป)';
        RAISE NOTICE 'เปิดเทอมใหม่ด้วย POST /api/v1/electives/terms {"year": ..., "semester": ...}';
    ELSE
        RAISE NOTICE 'เทอมที่กำลังจัด: %', term_label;
    END IF;
END $$;
