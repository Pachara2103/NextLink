-- ซึ่งเป็นปีไหนก็ได้ ปฏิทินจุฬา: ภาคต้นเริ่ม ส.ค. ภาคปลายเริ่ม ม.ค. ภาคฤดูร้อน
-- คาบเกี่ยว มิ.ย.-ก.ค. ปี พ.ศ. ของเทอมคือปีที่ "ภาคต้น" เริ่ม เดือน ม.ค.-ก.ค.
-- จึงยังนับเป็นปีการศึกษาที่แล้ว (+542 ไม่ใช่ +543)
--
-- ถ้ามีเทอมที่กำลังจัดอยู่แล้ว WHERE NOT EXISTS กันไว้ ส่วน ON CONFLICT กัน
-- กรณีที่เคยเปิดปี/ภาคนี้แล้วปิดไป - ไม่ใช่ความผิดพลาดที่ต้องหยุดทั้งไฟล์
-- --------------------------------------------------------------------------
INSERT INTO elective_terms (year, semester)
SELECT
    extract(year FROM now())::int
        + CASE WHEN extract(month FROM now()) >= 8 THEN 543 ELSE 542 END,
    CASE
        WHEN extract(month FROM now()) >= 8 THEN 1   -- ภาคต้น
        WHEN extract(month FROM now()) <= 5 THEN 2   -- ภาคปลาย
        ELSE 3                                       -- ภาคฤดูร้อน
    END
WHERE NOT EXISTS (SELECT 1 FROM elective_terms WHERE status = 'current')
ON CONFLICT ON CONSTRAINT uq_elective_terms_year_semester DO NOTHING;


